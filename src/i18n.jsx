const I18nContext = createContext(null);

function initialLocale() {
  const stored = localStorage.getItem(LANGUAGE_KEY);
  return stored === 'en' ? 'en' : 'zh';
}

export function I18nProvider({ children }) {
  const [locale, setLocale] = useState(initialLocale);

  useEffect(() => {
    localStorage.setItem(LANGUAGE_KEY, locale);
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
    document.documentElement.dataset.locale = locale;
    document.title = locale === 'en'
      ? 'Zhong Kui Archive | Black Myth: Zhong Kui'
      : '钟馗志｜《黑神话：钟馗》资料站';
  }, [locale]);

  const value = useMemo(() => ({
    locale,
    setLocale,
    toggleLocale: () => setLocale((current) => current === 'zh' ? 'en' : 'zh'),
    t(key, values = {}) {
      const template = copy[locale][key] ?? copy.zh[key] ?? key;
      return Object.entries(values).reduce((text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)), template);
    },
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used within I18nProvider');
  return value;
}

export function localizeItem(item, locale) {
  if (locale !== 'en') return item;
  return {
    ...item,
    title: item.titleEn ?? item.title,
    summary: item.summaryEn ?? item.summary,
    time: item.timeEn ?? item.time,
    platform: item.platformEn ?? item.platform,
    duration: item.durationEn ?? item.duration,
    tags: item.tagsEn ?? item.tags,
    links: item.links.map((link) => ({ ...link, label: link.labelEn ?? link.label })),
  };
}
